import { screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it, vi } from 'vitest';
import * as kd from '../api/knowledgeDrop';
import * as portalDb from '../api/portalDb';
import type { DocumentSummary } from '../api/types';
import { renderWithAuth } from '../test/helpers';
import { SummaryPanel } from './SummaryPanel';

const doc: DocumentSummary = {
  documentId: 'doc-1',
  filename: '340b-claims-policy.md',
  type: 'text/markdown',
  uploadTime: '2026-11-26T16:00:00Z',
  status: 'ready',
};

function renderPanel() {
  return renderWithAuth(
    <SummaryPanel
      doc={doc}
      ownerName="Priya Patel"
      nameOf={(id) => (id === 'a2' ? 'Priya Patel' : 'Unknown')}
      onClose={vi.fn()}
      onDownload={vi.fn()}
    />,
  );
}

describe('SummaryPanel', () => {
  it('shows a cached summary without calling the service', async () => {
    vi.spyOn(portalDb, 'getSummary').mockResolvedValue({
      document_id: 'doc-1',
      length: 'short',
      summary: 'Cached: 340B claims need SCC 20.',
      chunks_used: 3,
      created_by: 'a2',
      created_at: '2026-11-26T17:00:00Z',
    });
    const summarize = vi.spyOn(kd, 'summarize');

    renderPanel();

    expect(await screen.findByText('Cached: 340B claims need SCC 20.')).toBeInTheDocument();
    expect(screen.getByText(/generated by Priya Patel/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Regenerate' })).toBeInTheDocument();
    expect(summarize).not.toHaveBeenCalled();
  });

  it('generates and caches a summary when none is saved', async () => {
    vi.spyOn(portalDb, 'getSummary').mockResolvedValue(null);
    vi.spyOn(kd, 'summarize').mockResolvedValue({
      summary: 'Fresh summary.',
      documentId: 'doc-1',
      chunksUsed: 5,
    });
    const save = vi.spyOn(portalDb, 'saveSummary').mockResolvedValue();

    renderPanel();

    expect(await screen.findByText('Fresh summary.')).toBeInTheDocument();
    expect(kd.summarize).toHaveBeenCalledWith('kd-token', 'doc-1', 'short');
    await waitFor(() =>
      expect(save).toHaveBeenCalledWith('test.jwt.token', {
        document_id: 'doc-1',
        length: 'short',
        summary: 'Fresh summary.',
        chunks_used: 5,
        created_by: '11111111-1111-1111-1111-111111111111',
      }),
    );
  });

  it('explains a 501 and caches nothing', async () => {
    vi.spyOn(portalDb, 'getSummary').mockResolvedValue(null);
    vi.spyOn(kd, 'summarize').mockRejectedValue(new kd.KdError(501, 'Not Implemented', ''));
    const save = vi.spyOn(portalDb, 'saveSummary');

    renderPanel();

    expect(await screen.findByText(/Summaries aren't available/)).toBeInTheDocument();
    expect(save).not.toHaveBeenCalled();
  });

  it('loads the detailed summary separately when toggled', async () => {
    const getSummary = vi.spyOn(portalDb, 'getSummary').mockResolvedValue(null);
    vi.spyOn(kd, 'summarize').mockImplementation(async (_t, _id, length) => ({
      summary: `${length} summary`,
      documentId: 'doc-1',
      chunksUsed: 1,
    }));
    vi.spyOn(portalDb, 'saveSummary').mockResolvedValue();
    const user = userEvent.setup();

    renderPanel();
    expect(await screen.findByText('short summary')).toBeInTheDocument();

    await user.click(screen.getByRole('button', { name: 'Detailed' }));

    expect(await screen.findByText('detailed summary')).toBeInTheDocument();
    expect(getSummary).toHaveBeenLastCalledWith('test.jwt.token', 'doc-1', 'detailed');
    expect(screen.getByRole('button', { name: 'Detailed' })).toHaveAttribute('aria-pressed', 'true');
  });
});
